// bdEmu e2e: ++/-- and assignment operators on variables reached through pointers (address first, then memcpy), values of ++a / a++
struct V { int x; int y; };
int g[4];
void main() {
  int a = 5;
  int b;
  int arr[3];
  struct V v;
  struct V *p = &v;
  int *q = arr;
  char s[4];
  char *c = s;
  b = a++;
  trap_puti(b * 100 + a, "post=");
  b = ++a;
  trap_puti(b * 100 + a, "pre=");
  b = a--;
  trap_puti(b * 100 + a, "postd=");
  b = --a;
  trap_puti(b * 100 + a, "pred=");
  p->x = 10; p->y = 20;
  b = p->x++;
  trap_puti(b * 100 + p->x, "pp=");
  b = ++p->y;
  trap_puti(b * 100 + p->y, "pr=");
  p->x += 5; p->y *= 2;
  trap_puti(p->x * 100 + p->y, "cmp=");
  b = (p->x = 7);
  trap_puti(b * 100 + p->x, "as=");
  *q = 3; q[1] = 4; q[2] = *q + q[1];
  *q += 10; q[1]++; ++q[2];
  trap_puti(arr[0] * 10000 + arr[1] * 100 + arr[2], "arr=");
  g[2] = 9; g[2]--;
  trap_puti(g[2], "g=");
  c[0] = 'a'; c[1] = 'b';
  c[0]++; c[1] += 2;
  b = c[0]++;
  trap_puti(b * 1000 + c[0] * 10 + c[1] - 'a' * 10, "ch=");
  p->x = p->y = 4;
  trap_puti(p->x * 10 + p->y, "chain=");
}
